export function getBoard(id) {
  return PINOUT_BOARDS.find((b) => b.id === id);
}

/**
 * Search every board for a GPIO number, pin name or function. Returns
 * [{ board, pin }] in board order. A bare number such as "21" also matches GPIO21 / GP21 / PA21-style names.
 */
export function searchPins(query, boards = PINOUT_BOARDS) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return [];
  const numeric = /^\d+$/.test(q);
  const out = [];
  for (const board of boards) {
    for (const pin of board.pins) {
      const hay = `${pin.pin} ${pin.name} ${pin.fn}`.toLowerCase();
      let hit = hay.includes(q);
      if (!hit && numeric) hit = new RegExp(`(gpio|gp|p[a-c]|d|a)${q}(?!\\d)`, 'i').test(`${pin.pin} ${pin.name}`);
      if (hit) out.push({ board, pin });
    }
  }
  return out;
}
