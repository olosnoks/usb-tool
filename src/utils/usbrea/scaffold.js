export function _field(name) {
  const i = _ident(name);
  return i + (['raw', 'ok', 'error', 'checksum_ok'].includes(i) ? '_value' : '');
}

export function _ident(name) {
  const s = name.replace(/[^\p{L}\p{N}_]+/gu, '_').replace(/^_+|_+$/g, '').toLowerCase() || 'cmd';
  return /^\p{Nd}/u.test(s) ? 'cmd_' + s : s;
}

