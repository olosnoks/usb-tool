/** Python dict from a list of [key, value] with the None values dropped. */
function dropNone(pairs) {
  const o = {};
  for (const [k, v] of pairs) if (v !== null && v !== undefined) o[k] = v;
  return o;
}

/** The standalone pyusb driver (Python source) for a Protocol, as a string. */
export function generate(proto) {
  const vid = proto.vid !== null && proto.vid !== undefined ? `0x${fmt_hex(proto.vid, 4)}` : 'None  # TODO: set from lsusb';
  const pid = proto.pid !== null && proto.pid !== undefined ? `0x${fmt_hex(proto.pid, 4)}` : 'None  # TODO: set from lsusb';
  const ids = proto.vid !== null && proto.vid !== undefined ? `${fmt_hex(proto.vid, 4)}:${fmt_hex(proto.pid, 4)}` : '(unknown id)';
  const out = [py_format(HEADER, { vid, pid, ids, checksums: CHECKSUMS_PY })];
  const specs = [];

  function spec_of(c) {
    let setup = null;
    if (c.setup && c.setup.length) {
      const s = c.setup;
      setup = pytuple([s[0], s[1], s[2] | (s[3] << 8), s[4] | (s[5] << 8)]);
    }
    const fields = c.fields
      .filter((f) => ['value', 'bitfield', 'lookup', 'counter', 'checksum'].includes(f.kind))
      .map((f) => ({
        kind: f.kind, offset: f.offset, width: f.width, endian: f.endian, index: f.index,
        scale: pyfloat(nn(f.scale)), bias: pyfloat(nn(f.bias)),
        table: f.table ? new Map(dict_items(f.table).map(([k, v]) => [pyfloat(k), v])) : null,
        step: nn(f.step), algo: nn(f.algo), covers: pytuple(nn(f.covers)),
        bit_offset: nn(f.bit_offset), bit_width: nn(f.bit_width), source: nn(f.source),
      }));
    const t = c.template();
    return { template: hexOf(t), endpoint: c.endpoint, setup, fields };
  }

  // handshake links: session tokens a command copies from a handshake reply
  const links = new Map(); // `${command}\0${packet}` -> [field dict]
  const linkKey = (name, packet) => `${name}\0${packet}`;
  const getLinks = (name, packet) => links.get(linkKey(name, packet)) || [];

  function command_spec(c) {
    const spec = spec_of(c);
    spec.fields = spec.fields.concat(getLinks(c.name, 0));
    if (c.steps && c.steps.length) {
      spec.then = c.steps.map(spec_of);
      spec.then.forEach((x, i) => { x.fields = x.fields.concat(getLinks(c.name, i + 1)); });
    }
    return spec;
  }

  function reply_of(r, prefix) {
    let setup = null;
    if (r.source === 'control read' && r.query_setup && r.query_setup.length) {
      const q = r.query_setup;
      setup = pytuple([q[0], q[1], q[2] | (q[3] << 8), q[4] | (q[5] << 8), q[6] | (q[7] << 8)]);
    }
    const fields = r.fields.map((f) => {
      let name;
      if (f.kind === 'value' || f.kind === 'bitfield') name = prefix + (f.index ? `_${f.index}` : '');
      else if (f.name) name = _field(f.name);
      else name = `${f.kind}_${f.offset}`;
      return dropNone([
        ['kind', f.kind], ['name', name], ['offset', f.offset], ['width', f.width], ['endian', f.endian],
        ['const', nn(f.const)], ['echo', nn(f.echo)], ['scale', pyfloat(nn(f.scale))], ['bias', pyfloat(nn(f.bias))],
        ['algo', nn(f.algo)], ['covers', pytuple(nn(f.covers))], ['bit_offset', nn(f.bit_offset)],
        ['bit_width', nn(f.bit_width)], ['signed', f.signed ? true : null],
        ['table', f.kind === 'reading' && f.table ? new Map(dict_items(f.table)) : null],
      ]);
    });
    return { length: r.length, endpoint: r.endpoint, setup, after: r.packet, fields };
  }

  // handshake: replayed by Device.open(); session tokens are copied from this session's replies
  const hs = [];
  const notes = [];

  function hs_step(st) {
    let setup = null;
    if (st.setup) {
      const q = fromHex(st.setup);
      const a = [q[0], q[1], q[2] | (q[3] << 8), q[4] | (q[5] << 8)];
      if (st.read) a.push(q[6] | (q[7] << 8));
      setup = pytuple(a);
    }
    const fields = st.uses.map((u) => ({
      kind: 'session', offset: u.offset, width: u.width, endian: 'le', step: u.step - 1, at: u.reply_offset,
    }));
    const ck = st.request_checksum;
    if (ck) {
      const n = fromHex(st.request).length;
      fields.push({
        kind: 'checksum', offset: n - ck.width, width: ck.width, endian: ck.endian, algo: ck.algo, covers: pytuple(ck.covers),
      });
    }
    let reply = null;
    if (st.reply) {
      reply = { endpoint: st.reply_endpoint, length: fromHex(st.reply).length, expect: st.expect };
      if (st.reply_checksum) {
        const c = st.reply_checksum;
        reply.checksum = { algo: c.algo, width: c.width, endian: c.endian, covers: pytuple(c.covers) };
      }
    }
    const step = { template: st.request.replace(/ /g, ''), endpoint: st.endpoint, setup, read: Boolean(st.read), fields, reply };
    if (st.retries && st.retries.length) step.tries = st.retries.length + 1;
    const br = st.branches;
    if (br && (br.cases instanceof Map ? br.cases.size : Object.keys(br.cases).length)) {
      // the next steps depend on one byte of this step's reply, as the app did
      const cases = new Map();
      for (const [v, c] of dict_entries(br.cases)) {
        cases.set(parseInt(v, 16), c.main ? null : c.steps.map(hs_step));
      }
      step.branch = { offset: br.offset, default: parseInt(br.default, 16), cases };
      notes.push(`# step ${st.step} branches on reply byte ${br.offset} (values `
        + dict_entries(br.cases).map(([v]) => `0x${v}`).join(', ') + '); a value never captured falls back '
        + `to the most common branch, 0x${br.default}\n`);
    }
    return step;
  }

  for (const st of proto.handshake) {
    for (const t of st.tokens) {
      for (const u of t.used_by) {
        if ('command' in u) {
          const k = linkKey(u.command, u.packet);
          if (!links.has(k)) links.set(k, []);
          links.get(k).push({ kind: 'session', offset: u.offset, width: t.width, endian: 'le', step: st.step - 1, at: t.reply_offset });
        }
      }
    }
    hs.push(hs_step(st));
  }
  specs.push(hs.length ? '# handshake, evidence frames ' + proto.handshake.map((st) => st.frame).join(', ') + '\n' : '');
  for (const _x of notes) specs.push(_x);
  specs.push(`HANDSHAKE = ${py_repr(hs)}\n`);

  const queries = [];
  const qnames = new Map(); // reply -> driver method that asks for it
  const names = new Set(proto.commands.map((c) => _ident(c.name)));
  for (const r of proto.responses) {
    const ident = _ident(r.query);
    const cnst = ident.toUpperCase() + '_REPLY';
    specs.push(`${cnst} = ${py_repr(reply_of(r, ident))}\n`);
    const lines = r.fields.filter((f) => f.kind !== 'const').map((f) => `byte ${f.offset}: ${f.describe()}`).join('; ');
    const frames = r.samples.slice(0, 8).map((s) => s[3]).join(', ');
    const doc = `reply ${r.length} bytes; evidence frames ${frames}).\n\n        ${lines}`;
    if (r.source === 'command') {
      const c = proto.commands.find((x) => x.name === r.query);
      const args = Array.from({ length: c.arity }, (_, i) => `v${i}`).join(', ');
      const sig = args ? `self, ${args}` : 'self';
      const call = `${ident.toUpperCase()}, ${cnst}` + (args ? `, ${args}` : '');
      queries.push(py_format(QUERY, { name: `query_${ident}`, sig, call, doc: `Send ${r.query} and decode the device's reply (${doc}` }));
      continue;
    }
    const qname = !names.has(ident) ? `query_${ident}` : `query_${ident}_reply`;
    qnames.set(r.query, qname);
    let how, qarg;
    if (r.request !== null && r.request !== undefined) {
      const q = r.request;
      let sent, qspec;
      if (q.fields.some((f) => f.kind === 'unknown')) {
        sent = 'the first captured copy verbatim (its varying bytes could not be explained)';
        qspec = { template: q.samples[0][1].replace(/ /g, ''), endpoint: q.endpoint, setup: spec_of(q).setup, fields: [] };
      } else {
        sent = `\`${r.query_payload}\``;
        qspec = spec_of(q);
      }
      specs.push(`${ident.toUpperCase()} = ${py_repr(qspec)}\n`);
      how = `Send background poll ${sent}`;
      qarg = ident.toUpperCase();
    } else {
      how = `Read ${r.query} (control IN, setup ${hex(r.query_setup, ' ')})`;
      qarg = 'None';
    }
    queries.push(py_format(QUERY, { name: qname, sig: 'self', call: `${qarg}, ${cnst}`, doc: `${how} and decode the reply (${doc}` }));
  }

  const setters = new Set([
    ...proto.states.filter((r) => r.source !== 'reply').map((r) => r.state),
    ...proto.commands.filter((c) => c.switch).map((c) => c.switch.state),
  ]);
  for (const c of proto.commands) {
    const cnst = _ident(c.name).toUpperCase();
    const spec = command_spec(c);
    specs.push(`${cnst} = ${py_repr(spec)}\n`);
    const args = Array.from({ length: c.arity }, (_, i) => `v${i}`).join(', ');
    const sig = args ? `self, ${args}` : 'self';
    const frames = c.frames.slice(0, 8).join(', ');
    let lines = c.fields.filter((f) => f.kind !== 'const').map((f) => `byte ${f.offset}: ${f.describe()}`).join('; ');
    const send = `self._send(${cnst}${args ? ', ' + args : ''})`;
    let body = `return ${send}`;
    if (setters.has(c.name)) body = `r = ${send}\n        self.state[${py_str_repr(c.name)}] = float(v0)\n        return r`;
    const own = (c.requires || []).filter((r) => r.source !== 'reply');
    const rep = (c.requires || []).filter((r) => r.source === 'reply' && qnames.has(r.reply));
    let pre = own.map((r) => `self._require(${py_str_repr(r.state)}, ${stateRepr(r.value)}, self.set_${_ident(r.state)})\n        `).join('');
    for (const r of rep) {
      const want = r.flag ? Boolean(r.value) : r.value;
      const st = r.setter;
      const how = st ? `self.set_${_ident(st.command)}, ${stateRepr(st.value)}` : 'None';
      pre += `self._require_reported(self.${qnames.get(r.reply)}, ${py_str_repr(_field(r.state))}, ${py_repr(want)}, ${how})\n        `;
    }
    if (own.length) {
      lines += '\n\n        Only sent by the vendor app while ' + own.map(
        (r) => `${r.state} was ${fmt_g(r.value)} (frames ${r.frames.slice(0, 8).join(', ')})`).join(', ')
        + ': sets that first, or raises StateError with Device(auto_state=False).';
    }
    for (const r of rep) {
      const st = r.setter;
      lines += `\n\n        Only sent by the vendor app while the device reported ${r.state} ${fmt(r.value)} `
        + `(${r.reply} ${r.where}, replies in frames ${r.reply_frames.slice(0, 8).join(', ')}): `
        + `${qnames.get(r.reply)}() is read first` + (st
          ? `, and set_${_ident(st.command)}(${fmt(st.value)}) switches it when it differs`
          : ', and StateError is raised when it differs (no command changed it in the capture)') + '.';
    }
    const sw = c.switch;
    if (sw) {
      const setter = `self.set_${_ident(sw.state)}`;
      const back = sw.restore === 'previous'
        ? `if prev is not None:   # put back the ${sw.state} the device was in, as the app did\n            ${setter}(prev)\n        `
        : sw.restore !== null && sw.restore !== undefined ? `${setter}(${stateRepr(sw.restore)})\n        ` : '';
      pre += `prev = self.state.get(${py_str_repr(sw.state)})\n        ${setter}(${stateRepr(sw.enter)})\n        `;
      body = `r = ${send}\n        ${back}return r`;
      lines += `\n\n        The vendor app switched ${sw.state} to ${fmt(sw.enter)} inside this action `
        + `(frames ${sw.enter_frames.slice(0, 8).join(', ')})` + (sw.restore === 'previous'
          ? ` and back afterwards (frames ${sw.restore_frames.slice(0, 8).join(', ')}); the driver `
            + 'puts back the value it last set (none: the device stays in the new one)'
          : sw.restore !== null && sw.restore !== undefined ? ` and then to ${fmt(sw.restore)}` : '') + '.';
    }
    out.push(`
    def set_${_ident(c.name)}(${sig}):
        """${c.name} (${fmt_pct(c.confidence)} confidence; evidence frames ${frames}).

        ${lines}
        """
        ${pre}${body}
`);
  }
  for (const _x of queries) out.push(_x);
  if (proto.streams && proto.streams.length) {
    const streams = [];
    const tpl = (pattern) => pattern.split(/\s+/).filter(Boolean).map((b) => (/^[0-9a-f]{2}$/.test(b) ? b : '00')).join('');
    for (const st of proto.streams) {
      streams.push({
        format: st.format, endpoint: st.endpoint, chunk: st.chunk,
        endpoints: st.endpoints && st.endpoints.length ? st.endpoints : [st.endpoint],
        layout: nn(st.endpoint_layout), header_endpoint: nn(st.header_endpoint),
        padded: st.padded, header_len: st.header_len,
        first: tpl(st.first_header), next: tpl(st.next_header || st.first_header),
        count: st.count_offset, count_in_next: st.count_in_next,
        count_width: nn(st.count_width), count_endian: nn(st.count_endian),
        index: st.index_offset, index_base: st.index_base || 0,
        index_width: nn(st.index_width), index_endian: nn(st.index_endian),
        raw: Boolean(st.raw), size: nn(st.size), byteorder: nn(st.byteorder),
        channel_order: nn(st.channel_order),
        header_packet: st.header_packet ? tpl(st.header_packet) : null,
        inline: Boolean(st.header_inline),
        region: nn(st.region), length_field: nn(st.length_field),
        ack: st.ack ? { endpoint: st.ack.endpoint, length: st.ack.payload.split(/\s+/).filter(Boolean).length, expect: st.ack.payload } : null,
      });
    }
    specs.push('# image streams, first frames ' + proto.streams.map((st) => st.first_frames.join(', ')).join('; ') + '\n');
    specs.push(`STREAMS = ${py_repr(streams)}\n`);
    out.push(SEND_IMAGE);
  }
  const at = out[0].indexOf('class Device:');
  const head = out[0].slice(0, at);
  const cls = out[0].slice(at + 'class Device:'.length);
  const parser = proto.responses.length ? PARSER : '';
  out[0] = head + parser + '# ---- message specs (from inference) ----\n' + specs.join('') + '\n\nclass Device:' + cls;
  out.push(`

if __name__ == "__main__":
    import sys
    d = Device()
    name, *args = sys.argv[1:]
    fn = getattr(d, name) if name.startswith("query_") else getattr(d, "set_" + name)
    print(fn(*map(float, args)))
`);
  return out.join('');
}
