// Export a Test Runner suite as a standalone pySerial script, so it can be run
// outside the browser (CI, a bench PC). Pure string generation.

import { normalizeStep, parseHex } from './scriptModel';

const pyStr = (v) => JSON.stringify(String(v ?? '')); // JSON string literals are valid Python
const EOL = { none: '', cr: '\r', lf: '\n', crlf: '\r\n' };
const isOn = (v) => ['1', 'true', 'high', 'on'].includes(String(v).toLowerCase());

const PRELUDE = String.raw`#!/usr/bin/env python3
# Usage: python suite.py COM3 115200   (requires: pip install pyserial)
import re, sys, time
import serial

port = sys.argv[1] if len(sys.argv) > 1 else "COM3"
baud = int(sys.argv[2]) if len(sys.argv) > 2 else 115200
ser = serial.Serial(port, baud, timeout=0.05)
vars_ = {}
failures = 0

def expand(t):
    return re.sub(r"\$\{(\w+)\}", lambda m: str(vars_.get(m.group(1), m.group(0))), t)

def wait_for(pattern, mode, ci, timeout):
    flags = re.I if ci else 0
    end = time.time() + timeout
    buf = ""
    while time.time() < end:
        buf += ser.read(4096).decode("utf-8", "replace")
        if mode == "regex":
            m = re.search(pattern, buf, flags)
            if m:
                for i, g in enumerate(m.groups(), 1):
                    if g is not None: vars_[str(i)] = g
                return True
        else:
            needles = [expand(p) for p in pattern.split("||")] if mode in ("any", "not") else [expand(pattern)]
            hay = buf.lower() if ci else buf
            if any((n.lower() if ci else n) in hay for n in needles if n):
                return True
    return False

def run_step(n, send, is_hex, eol, pattern, mode, ci, timeout):
    ser.reset_input_buffer()
    if is_hex:
        data = bytes.fromhex(send) + eol.encode()
    else:
        data = (expand(send).encode("latin-1", "replace").decode("unicode_escape").encode("latin-1", "replace") if send else b"") + eol.encode()
    if data: ser.write(data)
    if not pattern: return True
    hit = wait_for(pattern, mode, ci, timeout)
    ok = (not hit) if mode == "not" else hit
    print("step %d: %s" % (n, "PASS" if ok else "FAIL"))
    return ok
`;

/**
 * Generate the script. Loops, retries and on-fail stop/continue are translated;
 * "goto" is not (noted in a comment, behaves as stop). Disabled steps are skipped.
 */
export function buildPySerialScript(suiteName, steps) {
  const L = [PRELUDE, `# Generated by Skon's USB Tool from the suite ${pyStr(suiteName)}.`, ''];
  steps.map(normalizeStep).forEach((s, idx) => {
    const n = idx + 1;
    if (s.disabled) { L.push(`# step ${n}: disabled, skipped`, ''); return; }
    if (s.onFail === 'goto') L.push(`# step ${n}: "goto" is not exported; this script stops on failure instead`);
    let body;
    if (s.type === 'delay') body = [`time.sleep(${(Number(s.value) || 0) / 1000})`, 'ok = True'];
    else if (s.type === 'dtr') body = [`ser.dtr = ${isOn(s.value) ? 'True' : 'False'}`, 'ok = True'];
    else if (s.type === 'rts') body = [`ser.rts = ${isOn(s.value) ? 'True' : 'False'}`, 'ok = True'];
    else if (s.type === 'baud') body = [`ser.baudrate = ${Number(s.value) || 115200}`, 'ok = True'];
    else {
      let send = s.send;
      if (s.sendFormat === 'hex') {
        try { send = parseHex(s.send).map((b) => b.toString(16).padStart(2, '0')).join(''); } catch { send = ''; }
      }
      body = [`ok = run_step(${n}, ${pyStr(send)}, ${s.sendFormat === 'hex' ? 'True' : 'False'}, ${pyStr(EOL[s.lineEnding] ?? '')}, ${pyStr(s.expect)}, ${pyStr(s.expectMode)}, ${s.caseSensitive ? 'False' : 'True'}, ${(s.timeoutMs || 0) / 1000})`];
    }
    const until = s.loopMode === 'until';
    L.push(`# step ${n}: ${s.type}${until ? `, repeat until matched (max ${s.loopCount})` : s.loopCount > 1 ? `, repeat ${s.loopCount}x` : ''}`);
    L.push(`for _rep in range(${s.loopCount}):`);
    L.push(`    for _try in range(${s.retries + 1}):`);
    body.forEach((b) => L.push(`        ${b}`));
    L.push('        if ok: break');
    L.push(until ? '    if ok: break' : '    if not ok: break');
    L.push('if not ok:');
    L.push('    failures += 1');
    if (s.onFail !== 'continue') L.push(`    print("step ${n} failed, stopping")`, '    sys.exit(1)');
    L.push('time.sleep(0.2)', '');
  });
  L.push('print("SUITE PASSED" if failures == 0 else "SUITE FAILED (%d step(s))" % failures)');
  L.push('sys.exit(1 if failures else 0)', '');
  return L.join('\n');
}
