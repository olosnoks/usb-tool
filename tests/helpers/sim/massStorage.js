// Test-only simulated USB Mass Storage (BOT/SCSI) transport + demo disk.
// Recovered from massStorageDriver.js (commit f695098^); serves a real FAT16
// image so the partition/file browser and SCSI parsing can be tested without a
// drive. Not imported by app code.
import { buildFatVolume, buildMbrDisk } from '../../../src/utils/diskImage.js';

const CBW_SIGNATURE = 0x43425355; // 'USBC'
const CSW_SIGNATURE = 0x53425355; // 'USBS'

export function buildDemoDisk() {
  const jpeg = new Uint8Array(3000);
  jpeg.set([0xff, 0xd8, 0xff, 0xe1, 0x00, 0x16, 0x45, 0x78, 0x69, 0x66, 0x00, 0x00]);
  jpeg.set([0xff, 0xd9], jpeg.length - 2);
  const volume = buildFatVolume({
    sectors: 14336,
    fatBits: 16,
    label: 'SIMUSB',
    files: [
      { path: 'README.TXT', data: 'This is a simulated drive.\r\nEverything on it was generated by the demo.\r\n' },
      { path: 'Meeting notes 2024.txt', data: 'Agenda:\n- firmware release\n- USB descriptor review\n' },
      { path: 'DCIM/100DEMO/IMG_0001.JPG', data: jpeg },
      { path: 'DCIM/100DEMO/IMG_0002.JPG', data: jpeg },
      { path: 'secret-plans.txt', data: 'Deleted, but the data is still on the disk until it is overwritten.\n', deleted: true }
    ]
  });
  return buildMbrDisk(volume, { startLba: 2048, type: 0x06 });
}

export function createSimulatedMassStorage() {
  const blockSize = 512;
  const disk = buildDemoDisk();
  const blocks = disk.length / blockSize;
  const state = { simulated: true, lastCdb: null };
  let pending = [];
  const push = (b) => pending.push(b);
  return {
    state,
    async open() {}, async close() {},
    async write(bytes) {
      const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
      if (dv.getUint32(0, true) !== CBW_SIGNATURE) return;
      const tag = dv.getUint32(4, true);
      const dataLen = dv.getUint32(8, true);
      const cdb = bytes.slice(15, 15 + bytes[14]);
      state.lastCdb = Array.from(cdb);
      const op = cdb[0];
      let data = null;
      if (op === 0x12) {
        data = new Uint8Array(36);
        data[0] = 0x00; data[1] = 0x80;
        new TextEncoder().encodeInto('SIMUSB  ', data.subarray(8));
        new TextEncoder().encodeInto('Virtual Disk', data.subarray(16));
        new TextEncoder().encodeInto('1.0 ', data.subarray(32));
      } else if (op === 0x25) {
        data = new Uint8Array(8); const d = new DataView(data.buffer);
        d.setUint32(0, blocks - 1, false); d.setUint32(4, blockSize, false);
      } else if (op === 0x28) {
        const lba = (cdb[2] << 24) | (cdb[3] << 16) | (cdb[4] << 8) | cdb[5];
        const count = (cdb[7] << 8) | cdb[8];
        data = disk.slice(lba * blockSize, (lba + count) * blockSize);
      } else if (op === 0x00) { data = new Uint8Array(); }
      if (data && data.length) push(data);
      const csw = new Uint8Array(13); const c = new DataView(csw.buffer);
      c.setUint32(0, CSW_SIGNATURE, true); c.setUint32(4, tag, true);
      c.setUint32(8, Math.max(0, dataLen - (data ? data.length : 0)), true); csw[12] = 0;
      push(csw);
    },
    async read() { return pending.length ? pending.shift() : new Uint8Array(); }
  };
}
